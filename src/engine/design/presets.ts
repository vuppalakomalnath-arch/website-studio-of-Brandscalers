export function getPresetForFamily(family: DesignFamily, preferredPreset?: string): { presetName: string; tokens: DesignTokens } {
  if (preferredPreset && DESIGN_PRESETS[preferredPreset]) {
    return { presetName: preferredPreset, tokens: DESIGN_PRESETS[preferredPreset] };
  }
  const defaultPresetName = FAMILY_TO_PRESETS[family][0] || 'Warm clinic';
  return { presetName: defaultPresetName, tokens: DESIGN_PRESETS[defaultPresetName] };
}
